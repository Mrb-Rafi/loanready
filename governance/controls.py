COSO: dict[str, str] = {row[0]: row[2] for row in _ROWS}
CONTROLS: tuple[ControlRow, ...] = tuple(
    ControlRow(
        control_id=cid,
        title=f"{title} (COSO {coso})",
        regulation_refs=list(regs),
        implemented_in=impl,
        tests=list(tests),
    )
    for cid, title, coso, regs, impl, tests in _ROWS
)


class Controls:
    """ControlsRegistry (WP1)."""

    def controls(self) -> list[ControlRow]:
        return list(CONTROLS)
