"""Framework-dependent labels and the accounting-policies note (PRD/05 §7, CTL-FR-08;
REG-ACC-01, -02, -04, -09, -12).

Wording rule (PRD/14 §4): the books are "designed around" / "aligned with" a framework,
never "compliant" or "certified".
"""

from __future__ import annotations

from contracts.enums import Framework

_LABELS: dict[Framework, dict[str, str]] = {
    Framework.IFRS_SME: {
        "balance_sheet": "Statement of financial position",
        "pnl": "Statement of profit or loss",
        "cash_flow": "Statement of cash flows",
        "allowance": "Impairment of trade receivables (allowance)",
        "impairment_expense": "Impairment loss on trade receivables",
        "interest_class": "financing",
    },
    Framework.US_GAAP: {
        "balance_sheet": "Balance sheet",
        "pnl": "Income statement",
        "cash_flow": "Statement of cash flows",
        "allowance": "Allowance for credit losses",
        "impairment_expense": "Credit loss expense",
        "interest_class": "operating",
    },
}


def labels(framework: Framework) -> dict[str, str]:
    return dict(_LABELS[Framework(framework)])


def policies(framework: Framework) -> list[str]:
    """The accounting-policies note for the loan pack (name used by the orchestrator)."""
    return accounting_policies(framework)


def accounting_policies(framework: Framework, currency: str = "USD") -> list[str]:
    """The policies note for the loan pack (REG-ACC-12): framework, accrual basis, revenue,
    inventory simplification, receivables impairment, cash definition, interest
    classification, functional currency and data provenance."""
    fw = Framework(framework)
    if fw == Framework.IFRS_SME:
        basis = (
            "Basis of preparation: these statements are designed around the IFRS for SMEs "
            "Accounting Standard (IASB). They are management accounts prepared by software, "
            "not audited financial statements."
        )
        revenue = (
            "Revenue: point-of-sale revenue is recognised at the time of sale; invoiced "
            "catering and wholesale revenue is recognised when the goods are delivered, which "
            "is the invoice date (aligned with IFRS for SMEs Section 23)."
        )
        impairment = (
            "Trade receivables: shown at invoiced amounts less any impairment allowance; "
            "receivables are monitored by ageing bucket (IFRS for SMEs Section 11)."
        )
        interest = (
            "Interest paid is classified as a financing cash flow (policy choice permitted by "
            "IFRS for SMEs paragraph 7.14)."
        )
        cash_flow = "The statement of cash flows uses the direct method (IFRS for SMEs 7.7)."
    else:
        basis = (
            "Basis of preparation: these statements are designed around US GAAP (FASB ASC) "
            "for private companies. They are management accounts prepared by software, not "
            "audited financial statements."
        )
        revenue = (
            "Revenue: point-of-sale revenue is recognised at the time of sale; invoiced "
            "revenue is recognised when the performance obligation is satisfied on delivery, "
            "the invoice date (aligned with ASC 606)."
        )
        impairment = (
            "Trade receivables: shown at invoiced amounts less an allowance for credit losses; "
            "receivables are monitored by ageing bucket (ASC 326-20)."
        )
        interest = "Interest paid is classified as an operating cash flow (ASC 230-10-45-17)."
        cash_flow = (
            "The statement of cash flows uses the direct method (ASC 230); a reconciliation "
            "of net income to operating cash flow is a planned addition."
        )
    return [
        basis,
        "Accrual basis: sales invoices and supplier bills are recognised when issued or "
        "received, not when paid; the cash view is given by the statement of cash flows.",
        revenue,
        "Inventories: ingredient and packaging purchases are expensed to cost of goods sold "
        "when bought (periodic, no stock count). This is a simplification of IFRS for SMEs "
        "Section 13 / ASC 330 and a stated limitation.",
        impairment,
        "Cash: cash at bank (account 1000) plus cash on hand in the till (account 1010). Card "
        "sales not yet settled are a receivable (1020).",
        interest,
        cash_flow,
        "Owner's personal spending paid from the business account is recorded as owner's "
        "drawings (equity), never as a business expense, after the owner confirms it.",
        "Corrections: posted journal entries are never edited; errors are corrected by a "
        "reversing entry and a new entry.",
        f"Functional and presentation currency: {currency}.",
        "Data provenance: generated by LoanReady from synthetic sandbox records (bank feed, "
        "point-of-sale sales, invoices, bills and receipts).",
    ]
